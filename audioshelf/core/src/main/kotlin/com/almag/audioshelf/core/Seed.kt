    fun library(now: Long, newId: () -> String): Library = Library(
        books = rows.map { (title, series, author, code) ->
            Book(
                id = newId(),
                title = title,
                series = series,
                author = author,
                status = statusOf(code),
                progress = if (code == L) 100 else 0,
                addedAt = now,
            )
        },
        authors = authors,
        series = series,
    )

    val size: Int get() = rows.size

    private fun statusOf(code: String) = when (code) {
        L -> Status.LISTENED
        P -> Status.LISTENING
        D -> Status.DROPPED
        else -> Status.WANT
